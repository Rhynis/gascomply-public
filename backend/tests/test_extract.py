# --- a from-scratch, dependency-free PDF writer, for this test file only ------------
#
# The standard Helvetica font this writer uses has no Vietnamese glyphs, so every
# non-ASCII character in the requested lines is remapped to a spare single byte
# (0x80 upward) and a /ToUnicode CMap on the font tells pypdf's text extraction how
# to read those bytes back as the real characters. This needs no embedded font file:
# /ToUnicode exists precisely so a text-extraction tool can recover the intended
# Unicode text even when a font's own encoding is unusual, which is exactly this case.

_CUSTOM_BYTE_START = 0x80


def _build_pdf(pages: Sequence[Sequence[str]]) -> bytes:
    """Build a minimal single-font PDF with one ``Tj`` text-show per given line.

    Each page's content stream is its own indirect object, referenced from the
    page object's ``/Contents``; the page's ``/Parent`` is patched in once the
    shared ``/Pages`` object's number is known, since PDF objects can only
    reference an object number that has already been assigned.
    """
    charmap = _assign_byte_codes(pages)
    objects: list[bytes] = []

    def add_object(body: bytes) -> int:
        objects.append(body)
        return len(objects)

    tounicode_num = add_object(_tounicode_cmap(charmap))
    font_num = add_object(
        b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica /ToUnicode "
        + str(tounicode_num).encode("ascii")
        + b" 0 R >>"
    )
    page_nums = [add_object(_page_object(lines, font_num, charmap, add_object)) for lines in pages]
    kids = b" ".join(f"{num} 0 R".encode("ascii") for num in page_nums)
    pages_num = add_object(
        b"<< /Type /Pages /Kids ["
        + kids
        + b"] /Count "
        + str(len(page_nums)).encode("ascii")
        + b" >>"
    )
    for num in page_nums:
        objects[num - 1] = objects[num - 1].replace(
            b"PAGES_REF", f"{pages_num} 0 R".encode("ascii")
        )
    catalog_num = add_object(
        b"<< /Type /Catalog /Pages " + str(pages_num).encode("ascii") + b" 0 R >>"
    )
    return _assemble_pdf(objects, catalog_num)


def _assign_byte_codes(pages: Sequence[Sequence[str]]) -> dict[str, int]:
    """Map every non-ASCII character used anywhere in ``pages`` to a spare byte."""
    chars = sorted({char for lines in pages for line in lines for char in line if ord(char) > 127})
    return {char: _CUSTOM_BYTE_START + index for index, char in enumerate(chars)}


def _tounicode_cmap(charmap: dict[str, int]) -> bytes:
    """Build a ``/ToUnicode`` CMap stream mapping each custom byte to its character."""
    entries = "\n".join(f"<{code:02X}> <{ord(char):04X}>" for char, code in charmap.items())
    cmap = (
        "/CIDInit /ProcSet findresource begin\n12 dict begin\nbegincmap\n"
        "/CIDSystemInfo << /Registry (Adobe) /Ordering (UCS) /Supplement 0 >> def\n"
        "/CMapName /Adobe-Identity-UCS def\n/CMapType 2 def\n"
        f"1 begincodespacerange\n<00> <FF>\nendcodespacerange\n"
        f"{len(charmap)} beginbfchar\n{entries}\nendbfchar\nendcmap\n"
        "CMapName currentdict /CMap defineresource pop\nend\nend"
    ).encode("ascii")
    return (
        b"<< /Length " + str(len(cmap)).encode("ascii") + b" >>\nstream\n" + cmap + b"\nendstream"
    )


def _page_object(
    lines: Sequence[str], font_num: int, charmap: dict[str, int], add_object: Callable[[bytes], int]
) -> bytes:
    """Add this page's content stream as its own object and return the ``/Page`` dict."""
    content_num = add_object(_content_stream(lines, charmap))
    return (
        b"<< /Type /Page /Parent PAGES_REF /MediaBox [0 0 612 792] "
        b"/Resources << /Font << /F1 " + str(font_num).encode("ascii") + b" 0 R >> >> "
        b"/Contents " + str(content_num).encode("ascii") + b" 0 R >>"
    )


def _content_stream(lines: Sequence[str], charmap: dict[str, int]) -> bytes:
    """Build a content stream that draws ``lines`` top to bottom, one ``Tj`` each."""
    ops = [b"BT", b"/F1 12 Tf"]
    y = 750
    for line in lines:
        shown = _pdf_escape(_encode_line(line, charmap))
        ops.append(b"72 " + str(y).encode("ascii") + b" Td (" + shown + b") Tj")
        y -= 16
    ops.append(b"ET")
    content = b"\n".join(ops)
    return (
        b"<< /Length "
        + str(len(content)).encode("ascii")
        + b" >>\nstream\n"
        + content
        + b"\nendstream"
    )


def _encode_line(line: str, charmap: dict[str, int]) -> bytes:
    """Encode one line, substituting each non-ASCII character's mapped byte."""
    return bytes(charmap.get(char, ord(char)) for char in line)


def _pdf_escape(data: bytes) -> bytes:
    """Backslash-escape the three bytes a PDF literal string cannot contain raw."""
    return data.replace(b"\\", rb"\\").replace(b"(", rb"\(").replace(b")", rb"\)")


def _assemble_pdf(objects: list[bytes], catalog_num: int) -> bytes:
    """Serialize numbered objects into a complete PDF with a valid xref table."""
    out = io.BytesIO()
    out.write(b"%PDF-1.4\n")
    offsets = [0]
    for index, body in enumerate(objects, start=1):
        offsets.append(out.tell())
        out.write(f"{index} 0 obj\n".encode("ascii"))
        out.write(body)
        out.write(b"\nendobj\n")
    xref_offset = out.tell()
    count = len(objects) + 1
    out.write(f"xref\n0 {count}\n".encode("ascii"))
    out.write(b"0000000000 65535 f \n")
    for offset in offsets[1:]:
        out.write(f"{offset:010d} 00000 n \n".encode("ascii"))
    out.write(b"trailer\n")
    out.write(f"<< /Size {count} /Root {catalog_num} 0 R >>\n".encode("ascii"))
    out.write(b"startxref\n")
    out.write(f"{xref_offset}\n".encode("ascii"))
    out.write(b"%%EOF")
    return out.getvalue()


def _write_pdf(tmp_path: Path, name: str, pages: Sequence[Sequence[str]]) -> Path:
    path = tmp_path / name
    path.write_bytes(_build_pdf(pages))
    return path


